import { test, expect, type Page } from '@playwright/test'
import { createHash } from 'node:crypto'
import { readFile } from 'node:fs/promises'

const api = 'http://127.0.0.1:8876/api/v1'
const claim = 'I reduced latency by 30% using Python'
const bullet = 'Reduced latency by 30% using Python'

async function navigate(page: Page, section: string) {
  await page.getByRole('navigation', { name: 'Main navigation' })
    .getByRole('button', { name: section, exact: true }).click()
}

test('reviewed resume intake → verified source → approved export → tracked application', async ({ page }) => {
  const errors: string[] = []
  const blockedRequests: string[] = []
  const allowedOrigins = new Set(['http://127.0.0.1:5174', 'http://127.0.0.1:8876'])
  await page.route('**/*', (route) => {
    const url = route.request().url()
    if (allowedOrigins.has(new URL(url).origin)) return route.continue()
    blockedRequests.push(url)
    return route.abort()
  })
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('dialog', (dialog) => { void dialog.accept() })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Your resume workspace.' })).toBeVisible()
  await expect(page.getByText('Loading workspace overview…')).toBeHidden()

  await navigate(page, 'Profile')
  await page.getByLabel('Name', { exact: true }).fill('Browser Fixture')
  await page.getByLabel('Email', { exact: true }).fill('fixture@example.test')
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Profile saved.')

  await navigate(page, 'Intake')
  const source = `Browser Fixture\nEngineer, Fictional Systems\n${claim}\n`
  await page.getByLabel('Resume file', { exact: false }).setInputFiles({
    name: 'fictional-resume.txt', mimeType: 'text/plain', buffer: Buffer.from(source),
  })
  await page.getByRole('button', { name: 'Preview file text' }).click()
  const text = page.getByRole('textbox', { name: 'Resume text', exact: true })
  await expect(text).toHaveValue(source.trim())
  await text.evaluate((element, selected) => {
    const input = element as HTMLTextAreaElement
    const start = input.value.indexOf(selected)
    input.focus(); input.setSelectionRange(start, start + selected.length)
  }, claim)
  await page.getByRole('button', { name: 'Use highlighted text as a claim' }).click()
  await expect(page.getByRole('textbox', { name: 'Selected claim', exact: true })).toHaveValue(claim)
  await page.getByLabel('Supporting source notes (optional)').fill('Fictional benchmark log, reviewed manually')
  await page.getByRole('button', { name: 'Create experience or project here' }).click()
  let contextForm = page.getByRole('form', { name: 'New source context' })
  await contextForm.getByLabel('Organization', { exact: true }).fill('Discarded context')
  await contextForm.getByRole('button', { name: 'Cancel source creation' }).click()
  await expect(text).toHaveValue(source.trim())
  await expect(page.getByRole('textbox', { name: 'Selected claim', exact: true })).toHaveValue(claim)
  expect(await (await page.request.get(`${api}/experiences`)).json()).toHaveLength(0)
  await page.getByRole('button', { name: 'Create experience or project here' }).click()
  contextForm = page.getByRole('form', { name: 'New source context' })
  await contextForm.getByLabel('Organization', { exact: true }).fill('Fictional Systems')
  await contextForm.getByLabel('Role title', { exact: true }).fill('Engineer')
  await contextForm.getByLabel('Start date', { exact: true }).fill('2023-06-30')
  await contextForm.getByLabel('End date', { exact: true }).fill('2020-01-01')
  await contextForm.getByRole('button', { name: 'Create source and select it' }).click()
  await expect(contextForm.getByRole('alert')).toContainText('End date must be after start date.')
  await expect(text).toHaveValue(source.trim())
  await expect(page.getByRole('textbox', { name: 'Selected claim', exact: true })).toHaveValue(claim)
  await contextForm.getByLabel('Start date', { exact: true }).fill('2020-01-01')
  await contextForm.getByLabel('End date', { exact: true }).fill('2023-06-30')
  await page.route(`${api}/experiences`, (route) => route.fulfill({
    status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Temporary fixture failure; retry safely' }),
  }), { times: 1 })
  await contextForm.getByRole('button', { name: 'Create source and select it' }).click()
  await expect(contextForm.getByRole('alert')).toContainText('Temporary fixture failure')
  await expect(text).toHaveValue(source.trim())
  await expect(page.getByRole('textbox', { name: 'Selected claim', exact: true })).toHaveValue(claim)
  await expect(contextForm.getByLabel('Organization', { exact: true })).toHaveValue('Fictional Systems')
  await contextForm.getByRole('button', { name: 'Create source and select it' }).click()
  await expect(contextForm).toBeHidden()
  await expect(page.getByRole('combobox', { name: 'Source experience or project', exact: true }).locator('option:checked')).toHaveText('Engineer · Fictional Systems')
  await expect(text).toHaveValue(source.trim())
  await expect(page.getByRole('textbox', { name: 'Selected claim', exact: true })).toHaveValue(claim)
  await expect(page.getByLabel('Supporting source notes (optional)')).toHaveValue('Fictional benchmark log, reviewed manually')
  await page.getByRole('button', { name: 'Save as draft evidence' }).click()
  await expect(page.getByText('Saved as draft evidence—not verified.', { exact: false })).toBeVisible()
  const imported = await (await page.request.get(`${api}/evidence`)).json()
  expect(imported).toHaveLength(1)
  expect(imported[0].state).toBe('draft')
  expect(imported[0].verified_at).toBeNull()
  await page.getByRole('button', { name: 'Open saved evidence' }).click()
  await expect(page.getByRole('textbox', { name: 'Claim', exact: true })).toHaveValue(claim)

  const metrics = page.locator('form').filter({ has: page.getByRole('heading', { name: 'Metrics', exact: true }) })
  await metrics.getByLabel('Name', { exact: true }).fill('Latency reduction')
  await metrics.getByLabel('Value', { exact: true }).fill('30')
  await metrics.getByLabel('Unit', { exact: true }).fill('%')
  await metrics.getByLabel('Metric source note').fill('Fictional benchmark log')
  await metrics.getByRole('button', { name: 'Add metric' }).click()
  await expect(page.getByRole('status')).toHaveText('Metric saved. Evidence returned to draft.')
  await page.getByRole('button', { name: 'Verify', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Evidence verified.')

  await navigate(page, 'Jobs')
  await page.getByLabel('Company', { exact: true }).fill('Fixture Employer')
  await page.getByLabel('Role title', { exact: true }).fill('Fixture role')
  await page.getByLabel('Original description', { exact: true }).fill('Python is required. Kubernetes is preferred.')
  await page.getByRole('button', { name: 'Save and extract requirements' }).click()
  await expect(page.getByRole('heading', { name: 'Fixture role · Fixture Employer' })).toBeVisible()
  const confirmations = page.getByRole('checkbox', { name: 'Confirmed', exact: true })
  await expect(confirmations).toHaveCount(2)
  for (const checkbox of await confirmations.all()) await checkbox.check()
  await page.getByRole('button', { name: 'Save requirement edits' }).click()
  await expect(page.getByRole('button', { name: 'Match verified evidence' })).toBeEnabled()
  await page.getByRole('button', { name: 'Match verified evidence' }).click()
  await expect(page.getByRole('heading', { name: 'Evidence match review' })).toBeVisible()
  await expect(page.getByText('No verified evidence found.', { exact: false })).toBeVisible()

  await navigate(page, 'Resumes')
  await page.getByRole('combobox', { name: 'Job', exact: true }).selectOption({ label: 'Fixture role · Fixture Employer' })
  await page.getByLabel('Resume name').fill('Browser test resume')
  await page.getByRole('button', { name: 'Create resume', exact: true }).click()
  await page.getByRole('checkbox', { name: claim, exact: true }).check()
  // A browser-visible failure case: an unsupported metric edit cannot create a version.
  await page.getByRole('textbox', { name: 'Bullet wording', exact: true }).fill('Reduced latency by 40% using Python')
  await page.getByRole('button', { name: 'Save draft version', exact: true }).click()
  await expect(page.getByText('Fix these issues before saving:', { exact: true })).toBeVisible()
  await expect(page.getByText('No versions saved yet.', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Bullet wording', exact: true }).fill(bullet)
  await page.getByRole('button', { name: 'Approve snapshot', exact: true }).click()
  await expect(page.getByLabel('Resume version').locator('option:checked')).toHaveText('Version 1 · approved')
  const preview = page.getByRole('article', { name: 'Resume preview version 1' })
  await expect(preview).toContainText('Browser Fixture')
  await expect(preview).toContainText(bullet)
  await page.getByRole('button', { name: 'Generate DOCX', exact: true }).click()
  const link = page.getByRole('link', { name: 'Download DOCX', exact: true })
  await expect(link).toBeVisible()
  const [download] = await Promise.all([page.waitForEvent('download'), link.click()])
  expect(download.suggestedFilename()).toBe('resume.docx')
  const downloadPath = await download.path()
  expect(downloadPath).not.toBeNull()
  const contents = await readFile(downloadPath!)
  expect(contents.subarray(0, 2).toString()).toBe('PK')
  const resumes = await (await page.request.get(`${api}/resumes`)).json()
  const versions = await (await page.request.get(`${api}/resumes/${resumes[0].id}/versions`)).json()
  expect(versions).toHaveLength(1)
  const exports = await (await page.request.get(`${api}/resume-versions/${versions[0].id}/exports`)).json()
  expect(createHash('sha256').update(contents).digest('hex')).toBe(exports[0].checksum)
  expect(exports[0].extracted_text).toContain(bullet)
  expect(exports[0].extracted_text).not.toContain('Kubernetes')
  await page.getByRole('button', { name: 'Run ATS readiness check' }).click()
  const ats = page.getByRole('region', { name: 'ATS readiness report' })
  await expect(ats).toContainText('Wording present')
  await expect(ats).toContainText('No direct verified evidence')

  await navigate(page, 'Applications')
  await page.getByRole('combobox', { name: 'Approved resume version', exact: true }).selectOption({ label: 'Fixture Employer · Fixture role · Browser test resume v1' })
  await page.getByRole('button', { name: 'Create application record' }).click()
  await expect(page.getByRole('heading', { name: 'Fixture role · Fixture Employer' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('applied')
  await page.getByLabel('History note for this update').fill('Submitted manually in browser fixture')
  await page.getByRole('button', { name: 'Save application', exact: true }).click()
  await expect(page.getByText('planned → applied', { exact: false })).toBeVisible()
  const applications = await (await page.request.get(`${api}/applications`)).json()
  expect(applications).toHaveLength(1)
  expect(applications[0].resume_version_id).toBe(versions[0].id)
  expect(applications[0].status).toBe('applied')
  await navigate(page, 'Dashboard')
  const recent = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Recent applications', exact: true }) })
  await recent.getByRole('button').click()
  await expect(page.getByRole('heading', { name: 'Linked resume · version 1' })).toBeVisible()
  // Also create an independent project in Intake without discarding the selected claim.
  await navigate(page, 'Intake')
  const projectClaim = 'Built a reporting pipeline'
  const projectText = page.getByRole('textbox', { name: 'Resume text', exact: true })
  await projectText.fill(projectClaim)
  await projectText.evaluate((element) => {
    const input = element as HTMLTextAreaElement
    input.focus(); input.select()
  })
  await page.getByRole('button', { name: 'Use highlighted text as a claim' }).click()
  await page.getByRole('button', { name: 'Create experience or project here' }).click()
  const projectForm = page.getByRole('form', { name: 'New source context' })
  await projectForm.getByRole('combobox', { name: 'New source type', exact: true }).selectOption('project')
  await projectForm.getByLabel('Project name', { exact: true }).fill('Browser personal project')
  await projectForm.getByRole('button', { name: 'Create source and select it' }).click()
  await expect(page.getByRole('combobox', { name: 'Source experience or project', exact: true }).locator('option:checked')).toHaveText('Browser personal project')
  await expect(projectText).toHaveValue(projectClaim)
  await page.getByRole('button', { name: 'Save as draft evidence' }).click()
  await page.getByRole('button', { name: 'Open saved evidence' }).click()
  await expect(page.getByRole('combobox', { name: 'Project', exact: true }).locator('option:checked')).toHaveText('Browser personal project')
  const projects = await (await page.request.get(`${api}/projects`)).json()
  expect(projects[0].experience_id).toBeNull()
  const projectEvidence = (await (await page.request.get(`${api}/evidence`)).json()).find((item: { claim: string }) => item.claim === projectClaim)
  expect(projectEvidence.state).toBe('draft')
  expect(projectEvidence.project_id).toBe(projects[0].id)
  expect(errors).toEqual([])
  expect(blockedRequests).toEqual([])
})
